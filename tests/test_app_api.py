import json
import threading
import unittest
from http.server import ThreadingHTTPServer
from unittest.mock import patch
from urllib.request import Request, urlopen

import app
from cortex_client import CortexClientError


class StubCortex:
    enabled = True

    def __init__(self):
        self.calls = []
        self.failure = None

    model = "test-model"

    def status(self):
        return {"enabled": True, "reachable": True, "ready": True, "model": self.model}

    def list_models(self):
        return [{"id": "test-model", "capabilities": ["text_generation"]}]

    def chat(self, messages, model=None):
        self.calls.append((messages, model))
        if self.failure:
            raise self.failure
        return "Generated by the local Cortex model.", "test-model"


class QuietPyBotHandler(app.PyBotHandler):
    def log_message(self, format_string, *args):
        pass


class PyBotCortexRoutingTests(unittest.TestCase):
    def setUp(self):
        self.cortex = StubCortex()
        self.patcher = patch.object(app, "CORTEX", self.cortex)
        self.patcher.start()
        self.server = ThreadingHTTPServer(("127.0.0.1", 0), QuietPyBotHandler)
        self.server.daemon_threads = True
        self.thread = threading.Thread(target=self.server.serve_forever, daemon=True)
        self.thread.start()
        self.url = f"http://127.0.0.1:{self.server.server_port}/api/chat"

    def tearDown(self):
        self.server.shutdown()
        self.server.server_close()
        self.thread.join(timeout=2)
        self.patcher.stop()

    def post(self, payload):
        request = Request(
            self.url,
            data=json.dumps(payload).encode("utf-8"),
            headers={"Content-Type": "application/json"},
        )
        with urlopen(request, timeout=3) as response:
            return json.load(response)

    def test_model_endpoint_exposes_only_safe_text_model_metadata(self):
        with urlopen(self.url.rsplit("/", 1)[0] + "/models", timeout=3) as response:
            payload = json.load(response)
        self.assertEqual(payload["selected"], "test-model")
        self.assertEqual(payload["models"], [{"id": "test-model", "capabilities": ["text_generation"]}])

    def test_open_ended_prompt_routes_to_cortex_with_history(self):
        result = self.post({
            "message": "Explain that again",
            "language": "fr-CA",
            "model": "fr-model",
            "history": [
                {"role": "user", "content": "What is photosynthesis?"},
                {"role": "assistant", "content": "It is how plants use light."},
            ],
        })
        self.assertEqual(result["reply"], "Generated by the local Cortex model.")
        self.assertEqual(result["provider"], "cortex")
        self.assertEqual(result["model"], "test-model")
        messages, selected_model = self.cortex.calls[0]
        self.assertEqual(selected_model, "fr-model")
        self.assertIn("fr-CA", messages[0]["content"])
        self.assertEqual(messages[-2]["content"], "It is how plants use light.")
        self.assertEqual(messages[-1]["content"], "Explain that again")

    def test_deterministic_commands_stay_local(self):
        result = self.post({
            "message": "Open kitchen lights!",
            "language": "en",
            "commands": [{
                "language": "en",
                "name": "Lights",
                "triggers": ["open kitchen lights"],
                "reply": "Kitchen lights are on.",
            }],
        })
        self.assertEqual(result["intent"], "custom_command")
        self.assertEqual(result["reply"], "Kitchen lights are on.")
        self.assertEqual(self.cortex.calls, [])

    def test_unavailable_cortex_uses_local_fallback_and_warning(self):
        self.cortex.failure = CortexClientError("offline", kind="unavailable")
        result = self.post({"message": "What is photosynthesis?", "language": "en"})
        self.assertEqual(result["provider"], "local-fallback")
        self.assertEqual(result["provider_warning"], "toast.cortexUnavailable")
        self.assertIn("local assistant mode", result["reply"])


if __name__ == "__main__":
    unittest.main()
